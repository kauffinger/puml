#!/usr/bin/env node
// Writes a deptrac configuration that expresses puml's architecture rules for one project. Regexes are
// written with a single backslash per namespace separator because ClassLikeConfig::create escapes them,
// so that deptrac can judge puml's verdict: node verify/deptrac-config.js <graph.json> <project-dir> > deptrac.php
// The rules and layer segments are read from the graph's verdict, as puml-extract judged them.

import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';

const [graphPath, projectDir] = process.argv.slice(2);

if (!projectDir) {
    console.error('usage: node verify/deptrac-config.js <graph.json> <project-dir>');
    process.exit(2);
}

const { rules, layer_segments: layerSegments } = JSON.parse(readFileSync(graphPath, 'utf8')).verdict;
const LAYER_SEGMENTS = Object.fromEntries(layerSegments.map((entry) => [entry.layer, entry.segments]));

const matchesSelector = (selector, place) =>
    selector.startsWith('segment:') ? place.layer === 'core' && place.segment === selector.slice('segment:'.length) : place.layer === selector;
const ruleBetween = (from, to) => rules.find((rule) => matchesSelector(rule.from, from) && matchesSelector(rule.to, to)) ?? null;

const composer = JSON.parse(readFileSync(resolve(projectDir, 'composer.json'), 'utf8'));
const roots = Object.entries(composer.autoload?.['psr-4'] ?? {}).map(([prefix, dir]) => ({
    prefix: prefix.replace(/\\$/, ''),
    dirs: [dir].flat().map((entry) => resolve(projectDir, entry)),
}));

const escape = (prefix) => prefix.replace(/\\/g, '\\\\');
const appRoots = roots.filter((root) => !root.prefix.startsWith('Database') && root.prefix !== 'Tests' && !root.prefix.startsWith('Tests\\'));
const databaseRoots = roots.filter((root) => root.prefix.startsWith('Database'));
const testRoots = roots.filter((root) => root.prefix === 'Tests' || root.prefix.startsWith('Tests\\'));
const alternation = (list) => `(${list.map(escape).join('|')})`;
const segmented = Object.values(LAYER_SEGMENTS).flat().concat(['Events', 'Listeners']);

const layers = [];

if (appRoots.length) {
    const prefix = alternation(appRoots.map((root) => root.prefix));

    for (const [layer, segments] of Object.entries(LAYER_SEGMENTS)) {
        layers.push({ name: layer, layer, segment: null, regex: `^${prefix}\\\\${alternation(segments)}\\\\` });
    }

    for (const segment of ['Events', 'Listeners']) {
        layers.push({ name: segment.toLowerCase(), layer: 'core', segment, regex: `^${prefix}\\\\${segment}\\\\` });
    }

    layers.push({ name: 'core', layer: 'core', segment: 'Other', regex: `^${prefix}\\\\(?!${alternation(segmented)}\\\\)` });
}

if (databaseRoots.length) {
    layers.push({ name: 'database', layer: 'database', segment: null, regex: `^${alternation(databaseRoots.map((root) => root.prefix))}\\\\` });
}

if (testRoots.length) {
    layers.push({ name: 'tests', layer: 'tests', segment: null, regex: `^${alternation(testRoots.map((root) => root.prefix))}\\\\` });
}

const variable = (layer) => `$${layer.name}`;
const rulesets = layers.map((from) => {
    const allowed = layers.filter((to) => to !== from && ruleBetween(from, to) === null);

    return `            Ruleset::forLayer(${variable(from)})->accesses(${allowed.map(variable).join(', ')}),`;
});

const php = `<?php

declare(strict_types=1);

// Generated by puml verify/deptrac-config.js from the verdict in ${graphPath}. Rules:
${rules.map((rule) => `//   ${rule.id}: ${rule.from} must not depend on ${rule.to}`).join('\n')}

use Deptrac\\Deptrac\\Contract\\Config\\AnalyserConfig;
use Deptrac\\Deptrac\\Contract\\Config\\Collector\\ClassLikeConfig;
use Deptrac\\Deptrac\\Contract\\Config\\DeptracConfig;
use Deptrac\\Deptrac\\Contract\\Config\\EmitterType;
use Deptrac\\Deptrac\\Contract\\Config\\Layer;
use Deptrac\\Deptrac\\Contract\\Config\\Ruleset;

return static function (DeptracConfig $config): void {
    $config
        ->paths(${roots.flatMap((root) => root.dirs).map((dir) => `'${dir}'`).join(', ')})
        ->analyser(AnalyserConfig::create([EmitterType::CLASS_TOKEN]))
        ->layers(
${layers.map((layer) => `            ${variable(layer)} = Layer::withName('${layer.name}')->collectors(ClassLikeConfig::create('${layer.regex}')),`).join('\n')}
        )
        ->rulesets(
${rulesets.join('\n')}
        );
};
`;

process.stdout.write(php);
